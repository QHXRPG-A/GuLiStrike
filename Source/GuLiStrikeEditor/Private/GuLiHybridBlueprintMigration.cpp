FString UGuLiHybridAuthoringLibrary::RetargetProductionPureCall(const FString& Path,const FString& GraphName,
    const FString& Guid,const FString& Fingerprint,const FString& ExpectedFunction,const FString& ReplacementFunction)
{
    auto J=MakeShared<FJsonObject>();J->SetBoolField(TEXT("saved"),false);J->SetBoolField(TEXT("compiled"),false);
    J->SetBoolField(TEXT("modified"),false);J->SetBoolField(TEXT("requires_blueprint_compile"),false);
    const auto Finish=[&](const FString& Error)
    {J->SetBoolField(TEXT("success"),Error.IsEmpty());J->SetStringField(TEXT("error"),Error);FString S;FJsonSerializer::Serialize(J,TJsonWriterFactory<>::Create(&S));return S;};
    if (!GEditor || GEditor->PlayWorld || !Path.StartsWith(TEXT("/Game/")) || Path.StartsWith(TEXT("/Game/Assets/")))
        return Finish(TEXT("Requires an idle editor and an explicit project Blueprint"));
    auto* BP=FindObject<UBlueprint>(nullptr,*Path);FGuid Id;
    if (!BP || !FGuid::Parse(Guid,Id) || !Id.IsValid()) return Finish(TEXT("Blueprint is not loaded or node identity is invalid"));
    TArray<UEdGraph*> Graphs;BP->GetAllGraphs(Graphs);UEdGraph* Graph=nullptr;
    for (auto* G:Graphs) if (G && G->GetName()==GraphName) {if (Graph) return Finish(TEXT("Graph name is ambiguous"));Graph=G;}
    if (!Graph || GuLiHybridAuthoring::ReadGraph(*Graph)->GetStringField(TEXT("fingerprint"))!=Fingerprint)
        return Finish(TEXT("Graph changed since review; inspect again before editing"));
    UK2Node_CallFunction* Old=nullptr;
    for (UEdGraphNode* N:Graph->Nodes) if (N && N->NodeGuid==Id) {if (Old) return Finish(TEXT("Duplicate node identity"));Old=Cast<UK2Node_CallFunction>(N);}
    auto* From=Old?Old->GetTargetFunction():nullptr;
    // Only native, already-loaded replacements are accepted. An asynchronous
    // transaction cannot masquerade as a same-signature synchronous pure call.
    auto* To=ReplacementFunction.StartsWith(TEXT("/Script/"))?FindObject<UFunction>(nullptr,*ReplacementFunction):nullptr;
    if (!From || From->GetPathName()!=ExpectedFunction || !To || From==To
        || !From->HasAllFunctionFlags(FUNC_BlueprintPure|FUNC_Static) || !To->HasAllFunctionFlags(FUNC_BlueprintPure|FUNC_BlueprintCallable|FUNC_Static))
        return Finish(TEXT("Expected a resolved pure call and a loaded native static pure replacement"));
    // Signature probe only; never become a serialized orphan node.
    auto* New=NewObject<UK2Node_CallFunction>(Graph,NAME_None,RF_Transient);
    New->SetFromFunction(To);New->AllocateDefaultPins();
    const auto IsImplicitSelf=[](const UEdGraphPin& Pin)
    {return Pin.PinName==UEdGraphSchema_K2::PN_Self && Pin.bHidden && Pin.LinkedTo.IsEmpty();};
    for (auto* Pin:Old->Pins) if (Pin && !IsImplicitSelf(*Pin))
    {
        auto* Replacement=New->FindPin(Pin->PinName,Pin->Direction);
        if (Pin->bOrphanedPin || !Pin->SubPins.IsEmpty() || Pin->ParentPin || !Replacement || Replacement->PinType!=Pin->PinType)
            return Finish(TEXT("Pin layout differs; requires explicit semantic graph migration"));
    }
    for (auto* Pin:New->Pins) if (Pin && !IsImplicitSelf(*Pin) && !Old->FindPin(Pin->PinName,Pin->Direction))
        return Finish(TEXT("Replacement introduces an unreviewed input/output"));
    const FScopedTransaction Edit(NSLOCTEXT("GuLiHybridAuthoring","RetargetPureCall","Migrate reviewed production Blueprint call"));
    BP->Modify();Graph->Modify();Old->Modify();Old->SetFromFunction(To);
    // Identical pins need no reconstruct: preserve GUIDs, node names, defaults,
    // links and comments. Only the unlinked static-library self pin changes.
    for (auto* Pin:Old->Pins) if (Pin && IsImplicitSelf(*Pin))
    {
        if (const auto* P=New->FindPin(Pin->PinName,Pin->Direction))
        {Pin->PinType=P->PinType;Pin->DefaultObject=P->DefaultObject;Pin->DefaultValue=P->DefaultValue;Pin->DefaultTextValue=P->DefaultTextValue;Pin->AutogeneratedDefaultValue=P->AutogeneratedDefaultValue;}
    }
    FBlueprintEditorUtils::MarkBlueprintAsModified(BP);
    J->SetBoolField(TEXT("modified"),true);J->SetBoolField(TEXT("requires_blueprint_compile"),true);
    J->SetStringField(TEXT("asset"),Path);J->SetStringField(TEXT("from"),ExpectedFunction);J->SetStringField(TEXT("to"),ReplacementFunction);
    // Saving source graphs deliberately leaves generated bytecode unchanged.
    // Do not mark the Blueprint up to date or trigger structural compilation.
    if (!UEditorLoadingAndSavingUtils::SavePackages({BP->GetOutermost()},true) || BP->GetOutermost()->IsDirty())
        return Finish(TEXT("Blueprint source changed but package save failed; inspect the dirty asset before retrying"));
    J->SetBoolField(TEXT("saved"),true);J->SetObjectField(TEXT("readback"),GuLiHybridAuthoring::ReadGraph(*Graph));
    return Finish(TEXT(""));
}
